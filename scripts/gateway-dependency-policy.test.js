const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { dependencies, overrides, stamp, repairBundledIpAddress, repairBundledDependencies, assertGatewayDependencyPolicy } = require('./lib/gateway-dependency-policy');

test('security policy satisfies transport peers and schema validation without changing the core or ClawHub', () => {
  assert.equal(dependencies.undici, '8.12.2');
  assert.equal(dependencies['undici-6'], 'npm:undici@6.29.1');
  assert.equal(dependencies.zod, '4.6.6');
  assert.equal(overrides['undici@7'], '7.30.1');
  assert.equal(overrides['undici@6'], '6.29.1');
  assert.equal(dependencies.openclaw, undefined);
  assert.equal(dependencies.clawhub, undefined);
  assert.equal(stamp, JSON.stringify({ dependencies, overrides }));
});
test('stale bundled IP parser updates only to a compatible safe installed replacement', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'cryoclaw-ip-policy-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const write = (relative, value) => { const p = path.join(dir, 'node_modules', relative, 'package.json'); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, JSON.stringify(value)); };
  write('ip-address', { name: 'ip-address', version: '10.7.4' });
  write('npm/node_modules/ip-address', { name: 'ip-address', version: '10.7.2' });
  write('npm/node_modules/socks', { name: 'socks', dependencies: { 'ip-address': '^10.0.1' } });
  assert.equal(repairBundledIpAddress(dir), true);
  assert.equal(fs.existsSync(path.join(dir, 'node_modules/ip-address/package.json')), true);
  assert.equal(repairBundledIpAddress(dir), false);
  write('npm/node_modules/ip-address', { name: 'ip-address', version: '10.7.2' });
  write('npm/node_modules/socks', { name: 'socks', dependencies: { 'ip-address': '^9' } });
  assert.throws(() => repairBundledIpAddress(dir), /Incompatible/);
  assert.equal(fs.existsSync(path.join(dir, 'node_modules/npm/node_modules/ip-address')), true);
});
test('bundled transport and lock bytes move to the safe 6.x line without changing root transport', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'cryoclaw-transport-policy-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const write = (relative, value) => { const p = path.join(dir, 'node_modules', relative, 'package.json'); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, JSON.stringify(value)); };
  write('undici', { name: 'undici', version: '8.12.2' });
  write('undici-6', { name: 'undici', version: '6.29.1' });
  write('openclaw/node_modules/undici', { name: 'undici', version: '8.11.2' });
  write('openclaw/node_modules/zod', { name: 'zod', version: '4.6.5' });
  write('openclaw/node_modules/consumer', { name: 'consumer', dependencies: { undici: '>=8.5.0 <9', zod: '^3.25.0 || ^4.0.0' } });
  write('npm/node_modules/undici', { name: 'undici', version: '6.29.0' });
  write('npm/node_modules/socks', { name: 'socks', dependencies: { undici: '^6.25.0' } });
  write('clawhub/node_modules/undici', { name: 'undici', version: '7.30.1' });
  write('ip-address', { name: 'ip-address', version: '10.7.4' });
  write('zod', { name: 'zod', version: '4.6.6' });
  fs.writeFileSync(path.join(dir, 'package-lock.json'), JSON.stringify({ packages: { 'node_modules/undici': { version: '8.12.2' }, 'node_modules/undici-6': { version: '6.29.1' }, 'node_modules/zod': { version: '4.6.6' } } }));
  const repaired = repairBundledDependencies(dir);
  assert.equal(repaired.undici, true);
  assert.equal(repaired.openclawUndici, true);
  assert.equal(repaired.openclawZod, true);
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir, 'node_modules/openclaw/node_modules/undici/package.json'), 'utf8')).version, '8.12.2');
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir, 'node_modules/openclaw/node_modules/zod/package.json'), 'utf8')).version, '4.6.6');
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir, 'node_modules/npm/node_modules/undici/package.json'), 'utf8')).version, '6.29.1');
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir, 'node_modules/undici/package.json'), 'utf8')).version, '8.12.2');
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir, 'package-lock.json'), 'utf8')).packages['node_modules/npm/node_modules/undici'].version, '6.29.1');
  assert.doesNotThrow(() => assertGatewayDependencyPolicy(dir));
  assert.equal(repairBundledDependencies(dir).undici, false);
});
